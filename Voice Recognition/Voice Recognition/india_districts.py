def get_all_states():
    """Return sorted list of all states/UTs."""
    return sorted(INDIA_DISTRICTS.keys())


def get_districts(state: str):
    """Return list of districts for a given state (case-insensitive)."""
    if not state:
        return []
    state_clean = state.strip()
    # Exact match first
    if state_clean in INDIA_DISTRICTS:
        return INDIA_DISTRICTS[state_clean]
    # Case-insensitive match
    state_lower = state_clean.lower()
    for key, val in INDIA_DISTRICTS.items():
        if key.lower() == state_lower:
            return val
    return []


def find_district(state: str, district_name: str):
    """Find a district by name within a state (case-insensitive). Returns dict or None."""
    districts = get_districts(state)
    if not districts or not district_name:
        return None
    district_lower = district_name.strip().lower()
    for d in districts:
        if d["name"].lower() == district_lower:
            return d
    return None
